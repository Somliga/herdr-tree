func kinds(nodes []adapter.Node) (ids []string, kinds []adapter.Kind, titles []string) {
	for _, n := range nodes {
		ids = append(ids, n.ID)
		kinds = append(kinds, n.Kind)
		titles = append(titles, n.Title)
	}
	return
}

func TestEntriesProjectsPromptsRepliesAndToolCalls(t *testing.T) {
	es, _, err := ParseFile("testdata/simple.jsonl")
	if err != nil {
		t.Fatal(err)
	}
	got := Entries(es)
	ids, ks, titles := kinds(got)
	wantIDs := []string{"u1", "a2", "u3", "a3"}
	if len(ids) != len(wantIDs) {
		t.Fatalf("got %v want %v", ids, wantIDs)
	}
	for i := range wantIDs {
		if ids[i] != wantIDs[i] {
			t.Fatalf("got %v want %v", ids, wantIDs)
		}
	}
	wantKinds := []adapter.Kind{adapter.KindHuman, adapter.KindToolCall, adapter.KindHuman, adapter.KindAssistant}
	for i := range wantKinds {
		if ks[i] != wantKinds[i] {
			t.Fatalf("node %d kind = %v want %v", i, ks[i], wantKinds[i])
		}
	}
	if titles[1] != "[bash]" {
		t.Fatalf("tool call title = %q, want the call not the output", titles[1])
	}
}

func TestToolCallRendersTheCallNotTheOutput(t *testing.T) {
	lines := []string{
		`{"type":"user","uuid":"u1","parentUuid":null,"sessionId":"S","message":{"role":"user","content":[{"type":"text","text":"read a file"}]}}`,
		`{"type":"assistant","uuid":"a1","parentUuid":"u1","sessionId":"S","requestId":"r1","message":{"role":"assistant","content":[{"type":"tool_use","id":"t1","name":"Read","input":{"file_path":"/home/x/notes.txt"}}]}}`,
		`{"type":"user","uuid":"tr1","parentUuid":"a1","sessionId":"S","toolUseResult":{"ok":true},"message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1"}]}}`,
	}
	var es []Entry
	for _, l := range lines {
		e, err := parseLine([]byte(l))
		if err != nil {
			t.Fatal(err)
		}
		es = append(es, e)
	}
	got := Entries(es)
	if len(got) != 2 {
		t.Fatalf("got %d nodes want 2 (prompt + call, never the result)", len(got))
	}
	if got[1].Title != "[read: /home/x/notes.txt]" {
		t.Fatalf("tool call title = %q", got[1].Title)
	}
}

