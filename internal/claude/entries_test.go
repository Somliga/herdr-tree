func TestOriginKindHumanIsPreferredOverHeuristics(t *testing.T) {
	// o2's text looks like injected bash-input scaffolding, which the
	// heuristic fallback would drop. Its origin.kind is "human" and the
	// transcript records origin at all, so the authoritative path must win.
	es, _, err := ParseFile("testdata/origin.jsonl")
	if err != nil {
		t.Fatal(err)
	}
	got := Entries(es)
	found := false
	for _, n := range got {
		if n.ID == "o2" {
			found = true
		}
		if n.ID == "skill1" {
			t.Fatalf("skill1 has no origin.kind:human, so it must be dropped even though the transcript has origin: %+v", n)
		}
	}
	if !found {
		t.Fatal("o2 has origin.kind human and must be kept despite its bash-input-shaped text")
	}
}

